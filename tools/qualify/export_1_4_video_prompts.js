// Builds tools/qualify/video_cases.json from the H3 prompt grammar of a 1.4 checkout,
// so that the 2.0 video engines are qualified on exactly the prompts 1.4 sends
// (cuts, Reference2Video, Relay). The subject and the sheets are those of
// image_cases.json: run both files in one go so '@sheet-human' etc. resolve.
//
//   node tools/qualify/export_1_4_video_prompts.js ../dellaicontent > tools/qualify/video_cases.json
//
// The 1.4 code is only executed to read its output; nothing of it is copied here.
"use strict";

const path = require("path");
const { execSync } = require("child_process");

const repo = path.resolve(process.argv[2] || "../dellaicontent");
require(path.join(repo, "js/engine.js"));
const E = globalThis.Engine;
const commit = execSync("git rev-parse --short HEAD", { cwd: repo }).toString().trim();

// Same subject as export_1_4_prompts.js (the sheets and shots of image_cases.json).
const STYLE = "cinematic";
const brief = "A lighthouse keeper repairing the lamp of an old stone lighthouse at dusk, storm clouds over the sea";
const charDesc = E.charDescFromFields({
  kind: "human",
  face: "a weathered man in his sixties with a short grey beard and deep-set blue eyes",
  hair: "short wavy grey hair",
  outfit: "a dark navy wool fisherman sweater, oilskin trousers and black rubber boots",
  accessories: "a brass pocket watch on a chain",
  palette: "navy, slate grey and brass",
});
const locDesc = E.locDescFromFields({
  place: "the lamp room at the top of an old stone lighthouse on a rocky coast",
  architecture: "a round room with tall windows all around and a huge Fresnel lens in the centre",
  materials: "whitewashed stone, brass fittings, worn wooden floor",
  lighting: "fading dusk light through the windows",
  palette: "slate blue, brass and warm white",
});
const subjects = [{ desc: charDesc, kind: "human" }];
const shot1 = { camera: "medium", lighting: "golden_hour", emotion: "calm concentration", extra: "",
  action: "the keeper kneels beside the great lens and tightens a brass screw with a small wrench" };
const shot2 = { camera: "close_up", lighting: "golden_hour", emotion: "relief", extra: "",
  action: "the keeper stands up, wipes his hands on a rag and watches the lamp flicker to life" };
const SECONDS = 5;   // FastVideo's MiniMax H3 minimum (1.4 cuts could be shorter)
const SEED = 42;
const cut = (shot, hasLast) => E.compileCutPromptFor(shot, subjects, locDesc, undefined, "minimax_h3", SECONDS, hasLast, STYLE);

// Reference2Video from the director session: sheet 1 = the character, sheet 2 = the setting.
const r2vSubjects = E.h3AssignSubjects([{ kind: "character", desc: charDesc }, { kind: "environment", desc: locDesc }]);
const r2v = E.capH3Prompt(E.buildH3RefPrompt({
  subjects: r2vSubjects, summary: E.h3Summary(brief), body: E.h3RefBody(r2vSubjects, brief),
}));

const cases = [
  { id: "r2v-preview", pipeline: "h3-r2v", compare: "first pass only (736×416): the quick look before the full render",
    params: { prompt: r2v, references: ["@sheet-human", "@sheet-setting"], duration: SECONDS, preview: true, seed: SEED } },
  { id: "r2v", pipeline: "h3-r2v",
    compare: "1.4 Reference2Video from sheets; the ComfyUI two-pass OmniRef workflow (1280×736, 5 s, about 260 s, face identity 0.838)",
    params: { prompt: r2v, references: ["@sheet-human", "@sheet-setting"], duration: SECONDS, seed: SEED } },
  { id: "cut-i2v", pipeline: "h3-i2v", compare: "1.4 storyboard cut, Minimax H3 engine, from the shot image",
    params: { prompt: cut(shot1, false), image: "@shot-2509-solo", duration: SECONDS, seed: SEED } },
  { id: "cut-fl2va", pipeline: "h3-i2v", compare: "1.4 Relay segment with an end image (FL2VA): the clip must land on the last image",
    params: { prompt: cut(shot1, true), image: "@shot-2509-solo", last_image: "@shot-21-solo", duration: SECONDS, seed: SEED } },
  { id: "relay-2", pipeline: "h3-i2v", compare: "1.4 Relay, continuous link: segment 2 starts from the last frame of segment 1",
    params: { prompt: cut(shot2, false), image: "@cut-i2v:1", duration: SECONDS, seed: SEED } },
  { id: "t2v", pipeline: "h3-t2v", compare: "1.4 Text2Video, Minimax H3, 16:9",
    params: { prompt: brief, aspect: "16:9", duration: SECONDS, seed: SEED } },
];

process.stdout.write(JSON.stringify({
  _comment: "Generated by export_1_4_video_prompts.js; '@<id>' stands for the first output of that case, "
    + "'@<id>:<n>' for its output n (1 = the last frame of a clip). Run after image_cases.json.",
  source: `yoyo-sama/dellaicontent@${commit}`,
  cases,
}, null, 2) + "\n");
