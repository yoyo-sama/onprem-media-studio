// Builds tools/qualify/relay_cases.json: a two-segment long take compiled by the Studio's
// own Relay code (web/js/prompts.js, buildRelaySegmentPrompt), so the GB10 renders exactly
// what "Generate the chain" sends. Self-contained: a Krea 2 still is the start image,
// segment 1 starts on it, segment 2 on segment 1's last frame (output 1 of its job, the
// default transition), then the two clips are joined.
//
//   node tools/qualify/export_relay_cases.js > tools/qualify/relay_cases.json
//   python tools/qualify/run_image_cases.py --cases relay_cases.json --report qualify-relay.json
"use strict";

const path = require("path");
const P = require(path.join(__dirname, "..", "..", "web", "js", "prompts.js"));

// The long take's subject is its start image, described once (Gemma's vision in the Studio).
const desc = "a woman in her thirties with short auburn hair, a green wool coat over a cream sweater, dark trousers and brown boots";
const look = {
  camera: "Medium shots at eye level.",
  lighting: "Soft cool overcast daylight with gentle diffuse shadows, the same throughout.",
  sound: "A light breeze, distant birdsong and soft footsteps on gravel.",
  music: "",
};
const segments = [
  "<Subject 1> walks slowly along a gravel garden path, looking around calmly; the camera tracks backward in front of <Subject 1>.",
  "<Subject 1> slows to a stop on the gravel path, turns toward the camera and smiles softly; slow push-in.",
];
const DURATION = 10;
const compare = "the light, the subject and the ambience hold across the join at 10.1 s; no golden-hour light, no music";
const prompt = (action, i) => P.buildRelaySegmentPrompt(action, look, [{ desc }], "", DURATION, false, "none", () => {
  throw new Error(`segment ${i + 1}: prompt over ${P.H3_PROMPT_CHARS} characters`);
});

const cases = [
  { id: "relay-start", pipeline: "krea2-t2i", compare: "start image of the long take",
    params: { prompt: `Photorealistic full-length photograph of ${desc}, standing on a gravel path in a walled garden with low stone walls and green hedges, soft cool overcast daylight, natural colours.`,
              width: 1280, height: 720, count: 1, seed: 501 } },
  ...segments.map((action, i) => ({
    id: `relay-seg-${i + 1}`, pipeline: "h3-i2v", compare,
    params: { prompt: prompt(action, i), duration: DURATION, seed: 501 + i, loras: [],
              image: i === 0 ? "@relay-start" : `@relay-seg-${i}:1` },
  })),
  { id: "relay-join", pipeline: "video-concat", compare: "the whole long take (about 20.3 s)",
    params: { clips: segments.map((_, i) => `@relay-seg-${i + 1}`) } },
];
process.stdout.write(JSON.stringify({ note: "Generated by tools/qualify/export_relay_cases.js from web/js/prompts.js.", cases }, null, 2) + "\n");
